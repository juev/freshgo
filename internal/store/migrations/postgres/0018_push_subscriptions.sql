-- The browsers of users that asked to be told of new entries: the address of
-- the push service that reaches the browser, and the keys the message to it is
-- encrypted with. An address names one browser, so it belongs to one user; a
-- user has a row for each browser.
CREATE TABLE push_subscriptions (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
	endpoint TEXT NOT NULL UNIQUE,
	p256dh TEXT NOT NULL,
	auth TEXT NOT NULL,
	created BIGINT NOT NULL
);
CREATE INDEX push_subscriptions_user ON push_subscriptions (user_id);
